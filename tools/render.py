"""Render everything generated from the manifests.

    python tools/render.py                 # compose.yml, endpoints map, catalog.html
    python tools/render.py --snippet NAME  # print a standalone compose file for one service

Output is deterministic (sorted keys and services, no timestamps) so diffs stay clean.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import jinja2
import yaml
from markupsafe import Markup

from tools import identity
from tools.schema import ASSETS_VAR, BASE_PATHS, MODELS_MOUNT, Manifest, Platform, PlatformError, load_platform
from tools.vram_check import BATCH_VARS, UTIL_VAR, VRAM_VAR

ASSETS_REF = "${AI_ASSETS:?set AI_ASSETS to the weights directory}"
HEADER = "# GENERATED by tools/render.py from services/*.yaml. Do not edit; run `just render`.\n"


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data: Any) -> bool:  # no &id001 anchors in generated files
        return True


def dump_yaml(obj: Any) -> str:
    return yaml.dump(obj, Dumper=_Dumper, sort_keys=True, default_flow_style=False, width=4096, allow_unicode=True)


def _assets(path: str) -> str:
    return path.replace(ASSETS_VAR, ASSETS_REF)


def _escape(arg: str) -> str:
    return arg.replace("$", "$$")  # compose would interpolate $ in commands


# A GPU service gets the whole GPU: the memory it asks for is measured right before its start and passed in
# as compose variables (tools/vram_check.py start_env). Without them, util_limit x gpu_total_gb.
_UTIL_MARK = "\0util\0"


def util_ref(p: Platform) -> str:
    return f"${{{UTIL_VAR}:-{p.config.util_limit:g}}}"


def vram_ref(p: Platform) -> str:
    return f"${{{VRAM_VAR}:-{p.config.util_limit * p.config.gpu_total_gb:.2f}}}"


# ----------------------------------------------------------------------------- compose

def labels(p: Platform, s: Manifest) -> dict[str, str]:
    return {
        "aiplatform.name": s.name,
        "aiplatform.kind": s.kind,
        "aiplatform.engine": s.engine,
        "aiplatform.contract": s.contract,
        "aiplatform.api": s.api,
        "aiplatform.image": p.image(s),
        "aiplatform.gpu": "true" if s.gpu else "false",
        "aiplatform.config_hash": identity.config_hash(p, s),  # the catalog's build key reads it
    }


def healthcheck(p: Platform, s: Manifest) -> dict[str, Any]:
    # curl is not guaranteed in every image; python3 is in vLLM, SGLang and both custom bases.
    url = f"http://127.0.0.1:{p.internal_port(s)}{p.health_path(s)}"
    probe = f"import urllib.request; urllib.request.urlopen('{url}', timeout=5)"
    return {
        "test": ["CMD", "python3", "-c", probe],
        "interval": "15s",
        "timeout": "10s",
        "retries": 3,
        "start_period": "5m" if s.is_custom else "15m",
        "start_interval": "5s",
    }


def compose_service(p: Platform, s: Manifest, compose_dir: Path, *, standalone: bool = False) -> dict[str, Any]:
    svc: dict[str, Any] = {
        "image": p.image(s),
        "ports": [f"127.0.0.1:{s.port}:{p.internal_port(s)}"],
        "networks": [p.config.network],
        "labels": labels(p, s),
        "healthcheck": healthcheck(p, s),
    }

    if s.is_custom:
        assert s.build is not None
        env = {"AISVC_NAME": s.name}
        if not standalone:
            build: dict[str, Any] = {"context": os.path.relpath(p.root / s.build.context, compose_dir)}
            base = p.base_image(s)
            if base:
                build["args"] = {"BASE_IMAGE": base}
            svc["build"] = build
        if s.weights:
            svc["volumes"] = [f"{_assets(s.weights.path)}:{s.weights.mount}:ro"]
            env["WEIGHTS_DIR"] = s.weights.mount
        if s.gpu:
            env["AISVC_VRAM_GB"] = vram_ref(p)
            env["AISVC_GPU_TOTAL_GB"] = f"{p.config.gpu_total_gb:g}"
            env.update({k: f"${{{v}:-}}" for k, v in BATCH_VARS.items()})  # set by the catalog from a batch profile
        svc["environment"] = env
    else:
        engine = p.engines[s.engine]
        assert s.model is not None
        util = _UTIL_MARK if s.gpu else None
        svc["command"] = [_escape(a).replace(_UTIL_MARK, util_ref(p))
                          for a in engine.render_command(model=s.model, name=s.name, util=util) + list(s.args)]
        # Engine models are local copies (schema), so the engine never needs the hub: offline makes a
        # missing file fail at start instead of being fetched into the container.
        svc["environment"] = {"HF_HUB_OFFLINE": "1", **engine.env}
        svc["volumes"] = [f"{ASSETS_REF}:{MODELS_MOUNT}:ro"]
        if engine.shm_size:
            svc["shm_size"] = engine.shm_size

    if s.gpu:
        svc["deploy"] = {"resources": {"reservations": {"devices": [
            {"driver": "nvidia", "count": 1, "capabilities": ["gpu"]}]}}}
    return svc


def build_compose(p: Platform, compose_dir: Path) -> dict[str, Any]:
    net = p.config.network
    return {
        "name": p.config.compose_project,
        "networks": {net: {"name": net, "external": True}},  # created by `just up` (tools/stack.py)
        "services": {s.name: compose_service(p, s, compose_dir) for s in p.services},
    }


def snippet(p: Platform, name: str) -> str:
    """Standalone compose file for one service: pushed image, no build context, own network."""
    s = p.get(name)
    net = p.config.network
    doc = {
        "name": s.name,
        "networks": {net: {"name": net}},
        "services": {s.name: compose_service(p, s, p.root, standalone=True)},
    }
    needs = ["AI_ASSETS (directory holding the weights)"]
    head = [
        f"# Standalone compose for {s.name} ({s.kind}, {s.contract}, {s.api}); generated by `just snippet {s.name}`.",
        f"# Needs env: {'; '.join(needs)}.",
    ]
    if s.is_custom:
        head.append(f"# Uses the pushed image {p.image(s)} (`just push {s.name}` first).")
    if s.weights:
        head.append(f"# Weights: {s.weights.path} (`just fetch-weights {s.name}`).")
    head.append(f"# Save as compose.yml, then: docker compose up -d   ->  http://127.0.0.1:{s.port}")
    return "\n".join(head) + "\n" + dump_yaml(doc)


# ----------------------------------------------------------------------------- endpoints map

def endpoint_entry(p: Platform, s: Manifest) -> dict[str, Any]:
    entry: dict[str, Any] = {
        "name": s.name,
        "alias": s.alias,
        "kind": s.kind,
        "contract": s.contract,
        "api": s.api,
        "engine": s.engine,
        "image": p.image(s),
        "host_port": s.port,
        "internal_port": p.internal_port(s),
        "base_path": BASE_PATHS[s.contract],
        "health_path": p.health_path(s),
        "description": s.description,
        "tasks": list(s.tasks),
        "gpu_fraction": round(s.vram_fraction(p.config.gpu_total_gb), 4),  # 0 for CPU services
        "labels": labels(p, s),
    }
    if s.signature:
        entry["signature"] = s.signature.model_dump(exclude_none=True)
    return entry


def build_endpoints(p: Platform) -> dict[str, Any]:
    services: dict[str, Any] = {}
    for s in p.services:
        for key in filter(None, (s.name, s.alias)):
            services[key] = endpoint_entry(p, s)
    return {"version": 1, "services": services}


# ----------------------------------------------------------------------------- catalog

def _py_value(arr_shape: list[int], datatype: str, example: list | None) -> str:
    np_dtype = {"FP32": "np.float32", "FP16": "np.float16", "FP64": "np.float64", "INT32": "np.int32",
                "INT64": "np.int64", "INT16": "np.int16", "INT8": "np.int8", "UINT8": "np.uint8",
                "BOOL": "np.bool_", "BYTES": "object"}.get(datatype, "np.float32")
    if example is not None:
        return f"np.array({example!r}, dtype={np_dtype})"
    shape = tuple(16000 if d == -1 else d for d in arr_shape)
    return f"np.zeros({shape[0] if len(shape) == 1 else shape}, dtype={np_dtype})"


def usage_snippet(s: Manifest) -> str:
    key = s.alias or s.name
    if s.contract == "openai":
        head = f'from aicore import client, model_name\n\nc = client("{key}")\n'
        body = {
            "chat.completions": f'r = c.chat.completions.create(\n    model=model_name("{key}"),\n'
                                f'    messages=[{{"role": "user", "content": "Hello!"}}],\n)\nprint(r.choices[0].message.content)',
            "completions": f'r = c.completions.create(model=model_name("{key}"), prompt="Once upon a time")\nprint(r.choices[0].text)',
            "embeddings": f'r = c.embeddings.create(model=model_name("{key}"), input=["hello", "world"])\n'
                          f'vectors = [d.embedding for d in r.data]',
            "audio.transcriptions": f'with open("speech.wav", "rb") as f:\n'
                                    f'    r = c.audio.transcriptions.create(model=model_name("{key}"), file=f)\nprint(r.text)',
            "audio.speech": f'r = c.audio.speech.create(model=model_name("{key}"), voice="alloy",\n'
                            f'                           input="Hello there!", response_format="wav")\nr.write_to_file("hello.wav")',
        }[s.api]
        return head + body
    if s.contract == "openai-inspired" and s.api == "text.itn":
        return (f'from aicore import client\n\nsvc = client("{key}")\n'
                f'svc.itn("meet at three thirty p m")                 # -> str\n'
                f'svc.itn(["twenty one", "noon"], return_spans=True)  # -> list of {{output, spans}} items')
    if s.contract == "openai-inspired":
        return (f'from aicore import client\n\nsvc = client("{key}")\n'
                f'svc.transform("hello world how are you")          # -> str\n'
                f'svc.transform(["a", "b"], terminal_punctuation=True)  # -> list[str]')
    assert s.signature is not None
    inputs = ",\n".join(f'    "{t.name}": {_py_value(t.shape, t.datatype, t.example)}' for t in s.signature.inputs)
    outs = "\n".join(f'out["{t.name}"]  # {t.datatype} {t.shape}' for t in s.signature.outputs)
    return (f'import numpy as np\nfrom aicore import client  # pip install "aicore[oip]"\n\n'
            f'svc = client("{key}")\nout = svc.infer({{\n{inputs},\n}})\n{outs}')


def catalog_data(p: Platform) -> dict[str, Any]:
    total = p.config.gpu_total_gb
    services = []
    for s in p.services:
        frac = s.vram_fraction(total)
        image = p.image(s)
        services.append({
            "name": s.name,
            "alias": s.alias,
            "kind": s.kind,
            "contract": s.contract,
            "contract_reason": s.contract_reason,
            "api": s.api,
            "engine": s.engine,
            "image": image,
            "engine_tag": image.rsplit(":", 1)[-1],
            "custom_reason": s.custom_reason,
            "model": s.model,
            "port": s.port,
            "base_url": f"http://localhost:{s.port}{BASE_PATHS[s.contract]}",
            "health_url": f"http://localhost:{s.port}{p.health_path(s)}",
            "gpu": None if s.gpu is None else {"fraction": round(frac, 4), "gb": round(frac * total, 2),
                                               "source": "util" if s.gpu.util is not None else "vram_gb"},
            "description": s.description,
            "tasks": list(s.tasks),
            "signature": s.signature.model_dump(exclude_none=True) if s.signature else None,
            "usage": usage_snippet(s),
            "snippet_cmd": f"just snippet {s.name}",
        })
    gpu = sorted(({"name": s["name"], **s["gpu"]} for s in services if s["gpu"]), key=lambda g: (-g["fraction"], g["name"]))
    return {"gpu_total_gb": total, "util_limit": p.config.util_limit, "services": services, "gpu": gpu}


def render_catalog(p: Platform) -> str:
    env = jinja2.Environment(loader=jinja2.FileSystemLoader(p.root / "ui"), autoescape=True,
                             keep_trailing_newline=True, undefined=jinja2.StrictUndefined)
    data = json.dumps(catalog_data(p), sort_keys=True, indent=1, ensure_ascii=False)
    data = data.replace("</", "<\\/")  # safe inside <script>
    return env.get_template("template.html.j2").render(data_json=Markup(data))


# ----------------------------------------------------------------------------- outputs

def outputs(p: Platform) -> dict[Path, str]:
    compose_dir = p.root / "compose" / "generated"
    return {
        compose_dir / "compose.yml": HEADER + dump_yaml(build_compose(p, compose_dir)),
        p.root / "clients" / "aicore" / "src" / "aicore" / "endpoints.generated.yaml": HEADER + dump_yaml(build_endpoints(p)),
        p.root / "ui" / "catalog.html": render_catalog(p),
    }


def write_outputs(p: Platform) -> list[Path]:
    written = []
    for path, text in outputs(p).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--snippet", metavar="NAME", help="print a standalone compose block for one service")
    args = ap.parse_args(argv)
    try:
        p = load_platform()
    except PlatformError as exc:
        print("validation FAILED, nothing rendered:\n  - " + "\n  - ".join(exc.errors), file=sys.stderr)
        return 1
    for w in p.warnings:
        print(f"warning: {w}", file=sys.stderr)
    if args.snippet:
        try:
            sys.stdout.write(snippet(p, args.snippet))
        except KeyError as exc:
            print(exc.args[0], file=sys.stderr)
            return 2
        return 0
    for path in write_outputs(p):
        print(f"rendered {path.relative_to(p.root)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
